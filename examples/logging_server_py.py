# FastMCP requires a dictionary so it can automatically format the final response into a valid JSON-RPC structure. log_event return

logger = logging.getLogger("mcp_logging_server")

DB_URI = os.getenv("DB_URI", "postgresql://user:password@localhost:5432/langgraph_db")

class LoggingServerDependencies:
    def __init__(self):
        self.pool: Optional[psycopg_pool.AsyncConnectionPool] = None

    @asynccontextmanager
    async def lifespan(self, server: FastMCP):
        logger.info("Initializing production database pool...")

        # Initialize connection pool with robust parameters
        self.pool = psycopg_pool.AsyncConnectionPool(
            conninfo=DB_URI,
            min_size=2,
            max_size=15,
            timeout=5.0,
            open=False
        )

        try:
            await self.pool.open()

            # Setup database tables and indexes safely
            async with self.pool.connection() as conn:
                async with conn.cursor() as cur:
                    await cur.execute(
                        """
                        CREATE TABLE IF NOT EXISTS logs (
                            id SERIAL PRIMARY KEY,
                            timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
                            log_type VARCHAR(255) NOT NULL,
                            message TEXT NOT NULL,
                            details JSONB NOT NULL DEFAULT '{}'::jsonb
                        );
                        """
                    )
                    await cur.execute("CREATE INDEX IF NOT EXISTS idx_logs_log_type ON logs(log_type);")
                # psycopg pool handles autocommit differently depending on config.
                # Explicitly commit the schema generation.
                await conn.commit()

            logger.info("Database validation completed successfully.")
        except Exception as e:
            logger.critical(f"Database setup failure: {e}", exc_info=True)
            # Force termination if the application cannot initialize its core storage layer
            sys.exit(1)

        yield  # Hand over execution control to the running FastMCP engine

        # Shutdown sequence
        if self.pool:
            logger.info("De-allocating connection pool variables...")
            await self.pool.close()

# Initialize State and Instance
server_state = LoggingServerDependencies()
mcp = FastMCP("MCP Logging Server", lifespan=server_state.lifespan)

