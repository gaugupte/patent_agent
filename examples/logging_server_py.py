@mcp.tool()
async def log_event(log_type: str, message: str, details: Optional[Dict[str, Any]] = None) -> dict:
    """Logs an operational system event to the central PostgreSQL database."""

    # Check pool validity safely
    if server_state.pool is None:
        return {"status": "error", "message": "Database pool unavailable."}

    sanitized_details = details if details is not None else {}

    try:
        # Request a healthy connection from the active pool
        async with server_state.pool.connection() as conn:
            async with conn.cursor() as cur:
                await cur.execute(
                    "INSERT INTO logs (log_type, message, details) VALUES (%s, %s, %s);",
                    (log_type, message, json.dumps(sanitized_details))
                )
            # Commit the transaction block safely
            await conn.commit()

        # FIX: Return a native dictionary object instead of stringified JSON.
        # FastMCP will natively format this into the proper JSON-RPC payload for utils.py.
        return {"status": "success", "message": "Log recorded."}

    except Exception as e:
        logger.error(f"Failed transaction execution: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}

if __name__ == "__main__":
    mcp.run()

